      function initSection(section) {
        var list = section.querySelector(".space-y-4");
        if (!list) return;
        var items = Array.from(list.children);

        items.forEach(function (item, index) {
          var btn = item.querySelector("button");
          if (!btn) return;

          var question = normalize(btn.querySelector("span") && btn.querySelector("span").textContent);
          var answer = FAQ_DATA[question];
          if (!answer) return;

          ensurePanel(item, answer);
          btn.type = "button";
          setOpen(item, index === 0);
        });
      }

      function handleClick(e) {
        var btn = e.target.closest(".scroll-mt-32 button");
        if (!btn) return;

        var item = btn.parentElement;
        var section = btn.closest(".scroll-mt-32");
        if (!item || !section) return;

        var list = section.querySelector(".space-y-4");
        if (!list || !list.contains(item)) return;

        var question = normalize(btn.querySelector("span") && btn.querySelector("span").textContent);
        if (!FAQ_DATA[question]) return;

        e.preventDefault();
        e.stopImmediatePropagation();

        var items = Array.from(list.children);
        var isOpen = btn.getAttribute("aria-expanded") === "true";

        items.forEach(function (other) {
          setOpen(other, false);
        });

        if (!isOpen) {
          setOpen(item, true);
        }
      }

      function init() {
        document.querySelectorAll(".scroll-mt-32").forEach(initSection);
        document.addEventListener("click", handleClick, true);
      }

      if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", init);
      } else {
        init();
      }
    })();
