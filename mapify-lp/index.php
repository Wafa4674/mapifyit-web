        if (!fullName) {
          showFieldError(form, "fullName", "Full name is required.");
          hasError = true;
        }

        if (!email) {
          showFieldError(form, "email", "Email address is required.");
          hasError = true;
        } else if (!emailPattern.test(email)) {
          showFieldError(form, "email", "Please enter a valid email address.");
          hasError = true;
        }

        if (!companyName && window.matchMedia("(max-width: 1023px)").matches) {
          showFieldError(form, "companyName", "Company name is required.");
